#!/usr/bin/env python3
"""Generates a standalone, reproducible Dockerfile_real at the ROOT of every
GROUNDTRUTH_VERIFIED task (sibling to ros1_code/ros2_code/tests), so the
groundtruth build+run check can be reproduced with a plain `docker build` --
no Python orchestration needed to prove it works.

Build context is the task directory itself, so the Dockerfile can COPY from
both ros2_code/source/ and tests/ (they're siblings, not nested).

Usage:
    python3 groundtruth_pipeline/generate_dockerfiles.py            # all verified tasks
    python3 groundtruth_pipeline/generate_dockerfiles.py --task <dir>

To actually build+run one:
    cd <task_dir>
    docker build -t gt-<task_name> -f Dockerfile_real .
    docker run --rm gt-<task_name>
"""

import argparse
import json
import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BASE_IMAGE = os.environ.get("GROUNDTRUTH_BASE_IMAGE", "groundtruth-base:humble")

TEMPLATE = """\
# Reproducible groundtruth build+run check for {task_name}.
# Generated by groundtruth_pipeline/generate_dockerfiles.py -- do not hand-edit;
# regenerate instead if ros2_code/source/ or tests/test_runtime_ros2.py change.
#
# Build:  docker build -t gt-{task_name} -f Dockerfile_real .
# Run:    docker run --rm gt-{task_name}
# (build context is this task's own directory)

FROM {base_image}

RUN mkdir -p /ros2_ws/src/{task_name}
COPY ros2_code/source/. /ros2_ws/src/{task_name}/
COPY tests/test_runtime_ros2.py /ros2_ws/src/{task_name}/test_runtime_ros2.py

WORKDIR /ros2_ws
RUN /bin/bash -c "source /opt/ros/humble/setup.bash && colcon build"

WORKDIR /ros2_ws/src/{task_name}
CMD ["/bin/bash", "-c", "source /opt/ros/humble/setup.bash && source /ros2_ws/install/setup.bash && pytest-3 test_runtime_ros2.py -q --tb=short"]
"""


def find_all_tasks():
    tasks = []
    for root, dirs, _ in os.walk(REPO_ROOT):
        if "ros1_code" in dirs and not root.endswith("/source"):
            tasks.append(Path(root))
    return sorted(tasks)


def is_groundtruth_verified(task_dir: Path) -> bool:
    status_path = task_dir / "ros2_code" / "GROUNDTRUTH_STATUS.json"
    if not status_path.exists():
        return False
    try:
        return json.loads(status_path.read_text()).get("status") == "GROUNDTRUTH_VERIFIED"
    except Exception:
        return False


def generate_for_task(task_dir: Path, base_image: str = BASE_IMAGE):
    content = TEMPLATE.format(task_name=task_dir.name, base_image=base_image)
    (task_dir / "Dockerfile_real").write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--task", type=str)
    args = parser.parse_args()

    if args.task:
        task_dirs = [Path(args.task)]
    else:
        task_dirs = [t for t in find_all_tasks() if is_groundtruth_verified(t)]

    for t in task_dirs:
        generate_for_task(t)
        print("wrote", t / "Dockerfile_real")

    print(f"\n{len(task_dirs)} Dockerfile_real written (base image: {BASE_IMAGE})")


if __name__ == "__main__":
    main()
