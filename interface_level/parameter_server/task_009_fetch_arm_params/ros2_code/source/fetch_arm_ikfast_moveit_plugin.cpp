bool IKFastKinematicsPlugin::computeRelativeTransform(const std::string& from, const std::string& to,
                                                      Eigen::Isometry3d& transform, bool& differs_from_identity)
{
  RobotStatePtr robot_state;
  robot_state.reset(new RobotState(robot_model_));

  auto* from_link = robot_state->getLinkModel(from);
  auto* to_link = robot_state->getLinkModel(to);
  if (!from_link)
    RCLCPP_ERROR_STREAM(node_->get_logger(), "Could not find frame " << from);
  if (!to_link)
    RCLCPP_ERROR_STREAM(node_->get_logger(), "Could not find frame " << to);
  if (!from_link || !to_link)
    return false;

  if (robot_state->getRobotModel()->getRigidlyConnectedParentLinkModel(from_link) !=
      robot_state->getRobotModel()->getRigidlyConnectedParentLinkModel(to_link))
  {
    RCLCPP_ERROR_STREAM(node_->get_logger(), "Link frames " << from << " and " << to << " are not rigidly connected.");
    return false;
  }

  transform = robot_state->getGlobalLinkTransform(from_link).inverse() * robot_state->getGlobalLinkTransform(to_link);
  differs_from_identity = !transform.matrix().isIdentity();
  return true;
}

bool IKFastKinematicsPlugin::initialize(const rclcpp::Node::SharedPtr& node,
                                        const moveit::core::RobotModel& robot_model,
                                        const std::string& group_name,
                                        const std::string& base_frame,
                                        const std::vector<std::string>& tip_frames,
                                        double search_discretization)
{
  // Store the node handle for parameter access and logging
  node_ = node;

  // Call the base class storeValues to cache group_name, base_frame, tip_frames, search_discretization
  storeValues(robot_model, group_name, base_frame, tip_frames, search_discretization);

  // Validate tip_frames: IKFast 6DOF solver supports exactly one tip frame
  if (tip_frames.size() != 1)
  {
    RCLCPP_ERROR(node_->get_logger(), "IKFast solver supports exactly one tip frame, but %zu were provided.",
                 tip_frames.size());
    return false;
  }

  // Declare and retrieve ROS 2 parameters using the node-based parameter API
  // robot_description is typically loaded elsewhere, but we declare it for completeness
  node_->declare_parameter<std::string>("robot_description", "");
  std::string robot_description;
  node_->get_parameter("robot_description", robot_description);

  // Declare solver-specific parameters
  node_->declare_parameter<double>("kinematics_solver_search_resolution", search_discretization);
  node_->declare_parameter<int>("kinematics_solver_attempts", 3);
  node_->declare_parameter<double>("kinematics_solver_timeout", 5.0);

  double search_res;
  node_->get_parameter("kinematics_solver_search_resolution", search_res);
  int solver_attempts;
  node_->get_parameter("kinematics_solver_attempts", solver_attempts);
  double solver_timeout;
  node_->get_parameter("kinematics_solver_timeout", solver_timeout);

  RCLCPP_INFO(node_->get_logger(), "IKFast kinematics plugin initializing for group '%s'", group_name.c_str());
  RCLCPP_INFO(node_->get_logger(), "  Base frame: %s", base_frame.c_str());
  RCLCPP_INFO(node_->get_logger(), "  Tip frame: %s", tip_frames[0].c_str());
  RCLCPP_INFO(node_->get_logger(), "  IKFast base frame: %s", IKFAST_BASE_FRAME_.c_str());
  RCLCPP_INFO(node_->get_logger(), "  IKFast tip frame: %s", IKFAST_TIP_FRAME_.c_str());
  RCLCPP_INFO(node_->get_logger(), "  Search discretization: %f", search_res);
  RCLCPP_INFO(node_->get_logger(), "  Solver attempts: %d", solver_attempts);
  RCLCPP_INFO(node_->get_logger(), "  Solver timeout: %f", solver_timeout);
  RCLCPP_INFO(node_->get_logger(), "  Number of joints in IKFast solver: %zu", num_joints_);
  RCLCPP_INFO(node_->get_logger(), "  IK type: %d", GetIkType());

  // Get the joint model group from the robot model
  const moveit::core::JointModelGroup* jmg = robot_model.getJointModelGroup(group_name);
  if (!jmg)
  {
    RCLCPP_ERROR(node_->get_logger(), "Could not find joint model group '%s'", group_name.c_str());
    return false;
  }

  // Get the active joint models for this group
  const std::vector<const moveit::core::JointModel*>& joint_models = jmg->getActiveJointModels();
  if (joint_models.size() != num_joints_)
  {
    RCLCPP_ERROR(node_->get_logger(),
                 "Joint model group '%s' has %zu active joints, but IKFast solver expects %zu.",
                 group_name.c_str(), joint_models.size(), num_joints_);
    return false;
  }

  // Extract joint names and limits
  joint_names_.clear();
  joint_min_vector_.clear();
  joint_max_vector_.clear();
  joint_has_limits_vector_.clear();
  link_names_.clear();

  for (size_t i = 0; i < joint_models.size(); ++i)
  {
    const moveit::core::JointModel* jm = joint_models[i];
    joint_names_.push_back(jm->getName());

    const moveit::core::VariableBounds& bounds = jm->getVariableBounds()[0];
    bool has_limits = bounds.position_bounded_;
    joint_has_limits_vector_.push_back(has_limits);

    if (has_limits)
    {
      joint_min_vector_.push_back(bounds.min_position_);
      joint_max_vector_.push_back(bounds.max_position_);
      RCLCPP_DEBUG(node_->get_logger(), "Joint '%s' has limits [%f, %f]",
                   jm->getName().c_str(), bounds.min_position_, bounds.max_position_);
    }
    else
    {
      joint_min_vector_.push_back(-M_PI);
      joint_max_vector_.push_back(M_PI);
    }
  }

  // Get link names
  const std::vector<const moveit::core::LinkModel*>& link_models = jmg->getLinkModels();
  for (const auto* lm : link_models)
  {
    link_names_.push_back(lm->getName());
  }

  // Fill free parameters from IKFast
  int num_free = GetNumFreeParameters();
  if (num_free > 0)
  {
    int* free_params_array = GetFreeParameters();
    fillFreeParams(num_free, free_params_array);

    // Set up redundant joint indices
    redundant_joint_indices_.clear();
    for (int i = 0; i < num_free; ++i)
    {
      redundant_joint_indices_.push_back(free_params_[i]);
    }

    // Set default discretization for redundant joints
    if (!redundant_joint_indices_.empty())
    {
      redundant_joint_discretization_[redundant_joint_indices_[0]] = search_discretization;
    }
  }

  // Determine if we need to compute transforms between the group frames and the IKFast frames
  // Check base frame offset
  if (base_frame != IKFAST_BASE_FRAME_)
  {
    RCLCPP_INFO(node_->get_logger(),
                "Base frame '%s' differs from IKFast base frame '%s', computing transform.",
                base_frame.c_str(), IKFAST_BASE_FRAME_.c_str());
    if (!computeRelativeTransform(base_frame, IKFAST_BASE_FRAME_, chain_base_to_group_base_, base_transform_required_))
    {
      RCLCPP_ERROR(node_->get_logger(),
                   "Could not compute transform from base frame '%s' to IKFast base frame '%s'.",
                   base_frame.c_str(), IKFAST_BASE_FRAME_.c_str());
      return false;
    }
  }
  else
  {
    base_transform_required_ = false;
    chain_base_to_group_base_ = Eigen::Isometry3d::Identity();
  }

  // Check tip frame offset
  if (tip_frames[0] != IKFAST_TIP_FRAME_)
  {
    RCLCPP_INFO(node_->get_logger(),
                "Tip frame '%s' differs from IKFast tip frame '%s', computing transform.",
                tip_frames[0].c_str(), IKFAST_TIP_FRAME_.c_str());
    if (!computeRelativeTransform(tip_frames[0], IKFAST_TIP_FRAME_, group_tip_to_chain_tip_, tip_transform_required_))
    {
      RCLCPP_ERROR(node_->get_logger(),
                   "Could not compute transform from tip frame '%s' to IKFast tip frame '%s'.",
                   tip_frames[0].c_str(), IKFAST_TIP_FRAME_.c_str());
      return false;
    }
  }
  else
  {
    tip_transform_required_ = false;
    group_tip_to_chain_tip_ = Eigen::Isometry3d::Identity();
  }

  initialized_ = true;
  RCLCPP_INFO(node_->get_logger(), "IKFast kinematics plugin successfully initialized.");
  return true;
}

void IKFastKinematicsPlugin::setSearchDiscretization(const std::map<unsigned int, double>& discretization)
{
  if (discretization.empty())
  {
    RCLCPP_ERROR(node_->get_logger(), "The 'discretization' map is empty");
    return;
  }

  if (redundant_joint_indices_.empty())
  {
    RCLCPP_ERROR_STREAM(node_->get_logger(), "This group's solver doesn't support redundant joints");
    return;
  }

  if (discretization.begin()->first != redundant_joint_indices_[0])
  {
    std::string redundant_joint = joint_names_[free_params_[0]];
    RCLCPP_ERROR_STREAM(node_->get_logger(), "Attempted to discretize a non-redundant joint "
                                      << discretization.begin()->first << ", only joint '" << redundant_joint
                                      << "' with index " << redundant_joint_indices_[0] << " is redundant.");
    return;
  }

  if (discretization.begin()->second <= 0.0)
  {
    RCLCPP_ERROR_STREAM(node_->get_logger(), "Discretization can not takes values that are <= 0");
    return;
  }

  redundant_joint_discretization_.clear();
  redundant_joint_discretization_[redundant_joint_indices_[0]] = discretization.begin()->second;
}

