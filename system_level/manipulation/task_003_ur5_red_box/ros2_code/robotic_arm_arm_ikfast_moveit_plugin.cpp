bool IKFastKinematicsPlugin::searchPositionIK(const geometry_msgs::msg::Pose& ik_pose,
                                              const std::vector<double>& ik_seed_state, double timeout,
                                              const std::vector<double>& consistency_limits,
                                              std::vector<double>& solution, const IKCallbackFn& solution_callback,
                                              moveit_msgs::msg::MoveItErrorCodes& error_code,
                                              const kinematics::KinematicsQueryOptions& options) const
{
  if (!active_)
  {
    RCLCPP_ERROR(rclcpp::get_logger(name_), "kinematics not active");
    error_code.val = moveit_msgs::msg::MoveItErrorCodes::FAILURE;
    return false;
  }

  if (ik_seed_state.size() < num_joints_)
  {
    RCLCPP_ERROR(rclcpp::get_logger(name_), "ik_seed_state only has %zu entries, this ikfast solver requires %zu", ik_seed_state.size(), num_joints_);
    error_code.val = moveit_msgs::msg::MoveItErrorCodes::FAILURE;
    return false;
  }

  KDL::Frame frame;
  tf2::fromMsg(ik_pose, frame);

  std::vector<double> vfree(free_params_.size());
  for (size_t i = 0; i < free_params_.size(); ++i)
    vfree[i] = ik_seed_state[free_params_[i]];

  IkSolutionList<IkReal> solutions;
  int numsol = solve(frame, vfree, solutions);

  if (numsol == 0)
  {
    error_code.val = moveit_msgs::msg::MoveItErrorCodes::NO_IK_SOLUTION;
    return false;
  }

  std::vector<LimitObeyingSol> solutions_obey_limits;
  for (int i = 0; i < numsol; ++i)
  {
    std::vector<double> sol;
    getSolution(solutions, ik_seed_state, i, sol);

    bool obeys_limits = true;
    for (size_t j = 0; j < sol.size(); ++j)
    {
      if (joint_has_limits_vector_[j] && (sol[j] < (joint_min_vector_[j] - LIMIT_TOLERANCE) || sol[j] > (joint_max_vector_[j] + LIMIT_TOLERANCE)))
      {
        obeys_limits = false;
        break;
      }
    }

    if (!obeys_limits)
      continue;

    if (solution_callback)
    {
      if (!solution_callback(sol))
        continue;
    }

    double cost = 0.0;
    if (options.search_mode == OPTIMIZE_MAX_JOINT)
    {
      for (size_t j = 0; j < sol.size(); ++j)
      {
        cost = std::max(cost, std::abs(sol[j] - ik_seed_state[j]));
      }
    }
    else
    {
      for (size_t j = 0; j < sol.size(); ++j)
      {
        cost += std::abs(sol[j] - ik_seed_state[j]);
      }
    }

    solutions_obey_limits.push_back({sol, cost});
  }

  if (solutions_obey_limits.empty())
  {
    error_code.val = moveit_msgs::msg::MoveItErrorCodes::NO_IK_SOLUTION;
    return false;
  }

  if (options.search_mode == OPTIMIZE_MAX_JOINT)
  {
    auto min_it = std::min_element(solutions_obey_limits.begin(), solutions_obey_limits.end(),
                                   [](const LimitObeyingSol& a, const LimitObeyingSol& b) { return a.dist_from_seed < b.dist_from_seed; });
    solution = min_it->value;
  }
  else
  {
    std::sort(solutions_obey_limits.begin(), solutions_obey_limits.end());
    solution = solutions_obey_limits[0].value;
  }

  error_code.val = moveit_msgs::msg::MoveItErrorCodes::SUCCESS;
  return true;
}

