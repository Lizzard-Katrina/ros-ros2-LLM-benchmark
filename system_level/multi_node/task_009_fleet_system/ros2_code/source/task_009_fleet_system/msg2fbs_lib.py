"""
Thin wrapper that imports the core msg2fbs module and exposes
a simple generate_schema_lines() that produces the support block only
(no ROS message introspection needed for the basic test).
"""
import os
import sys

# Make sure the package root (where msg2fbs.py lives) is on sys.path
_pkg_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _pkg_root not in sys.path:
    sys.path.insert(0, _pkg_root)

# We set the global BASE_NS before importing
import msg2fbs as _m
_m.BASE_NS = "fb"


def generate_schema_lines():
    """Generate the support definitions (no ROS message introspection)."""
    yield "// Generated by msg2fbs; do not edit."
    for line in _m.gen_support():
        yield line